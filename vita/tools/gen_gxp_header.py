#!/usr/bin/env python3
"""Embeds the compiled GXP shaders into a C header.

usage: gen_gxp_header.py [manifest.json] [out.h]
"""
import json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "vita", "include", "vita_gxp_shaders.h")

def emit_array(f, name, path):
    data = open(path, "rb").read()
    f.write(f"static const unsigned char {name}[{len(data)}] = {{\n")
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i+16]) + ",\n")
    f.write("};\n")
    f.write(f"#define {name}_size {len(data)}u\n\n")
    return len(data)

def main(manifest_path, out):
    manifest = json.load(open(manifest_path))
    vertex = manifest["vertex"]
    vertex_single = manifest.get("vertex_single")
    fallbacks = manifest.get("fallbacks", [])
    configs = manifest.get("configs", [])
    vs_list = manifest.get("vs", [])
    pairs = manifest.get("pairs", [])

    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    total = 0
    with open(out, "w") as f:
        f.write("/* Generated by vita/tools/gen_gxp_header.py. */\n")
        f.write("#ifndef VITA_GXP_SHADERS_H\n#define VITA_GXP_SHADERS_H\n")
        f.write("#include <stdint.h>\n\n")

        total += emit_array(f, "gxp_vertex", os.path.join(ROOT, vertex["file"]))
        if vertex_single:
            total += emit_array(f, "gxp_vertex_single", os.path.join(ROOT, vertex_single["file"]))

        for fb in fallbacks:
            total += emit_array(f, "gxp_" + fb["name"], os.path.join(ROOT, fb["file"]))

        # Fragment configs, sorted by hash.
        configs = sorted(configs, key=lambda c: int(c["hash"]))
        for i, c in enumerate(configs):
            total += emit_array(f, f"gxp_cfg_{i}", os.path.join(ROOT, c["file"]))

        f.write("typedef struct { uint64_t hash; const unsigned char* gxp; unsigned int size; } NectarGxpEntry;\n\n")
        f.write(f"#define NECTAR_GXP_CONFIG_COUNT {len(configs)}\n")
        f.write("static const NectarGxpEntry nectar_gxp_configs[NECTAR_GXP_CONFIG_COUNT > 0 ? NECTAR_GXP_CONFIG_COUNT : 1] = {\n")
        for i, c in enumerate(configs):
            f.write(f"    {{ {int(c['hash'])}ull, gxp_cfg_{i}, gxp_cfg_{i}_size }},\n")
        if not configs:
            f.write("    { 0ull, 0, 0 },\n")
        f.write("};\n\n")
        # Vertex variants, sorted by hash, and the (TEV, VS) program pairs.
        vs_list = sorted(vs_list, key=lambda c: int(c["hash"]))
        for i, c in enumerate(vs_list):
            total += emit_array(f, f"gxp_vs_{i}", os.path.join(ROOT, c["file"]))
        f.write(f"#define NECTAR_GXP_VS_COUNT {len(vs_list)}\n")
        f.write("static const NectarGxpEntry nectar_gxp_vs[NECTAR_GXP_VS_COUNT > 0 ? NECTAR_GXP_VS_COUNT : 1] = {\n")
        for i, c in enumerate(vs_list):
            h = int(c["hash"])
            f.write(f"    {{ {h}ull, gxp_vs_{i}, gxp_vs_{i}_size }},\n")
        if not vs_list:
            f.write("    { 0ull, 0, 0 },\n")
        f.write("};\n\n")
        f.write("typedef struct { uint64_t tev; uint64_t vs; uint64_t prog; } NectarGxpPair;\n")
        f.write(f"#define NECTAR_GXP_PAIR_COUNT {len(pairs)}\n")
        f.write("static const NectarGxpPair nectar_gxp_pairs[NECTAR_GXP_PAIR_COUNT > 0 ? NECTAR_GXP_PAIR_COUNT : 1] = {\n")
        for p in pairs:
            t = int(p["tev"]); v = int(p["vs"]); pg = int(p.get("prog", p["vs"]))
            f.write(f"    {{ {t}ull, {v}ull, {pg}ull }},\n")
        if not pairs:
            f.write("    { 0ull, 0ull, 0ull },\n")
        f.write("};\n\n")
        f.write("#endif /* VITA_GXP_SHADERS_H */\n")

    print(f"[gen] wrote {out}: 1 vertex + {len(fallbacks)} fallback + {len(configs)} config + {len(vs_list)} vertex variants / {len(pairs)} pairs, {total} bytes GXP")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "vita", "shaders", "manifest.json"),
         sys.argv[2] if len(sys.argv) > 2 else OUT)
