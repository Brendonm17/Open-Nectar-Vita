#include <cstdarg>
#include <cstdio>
#include <string>

namespace {

void addf(std::string& out, const char* fmt, ...) {
	char buf[1024];
	va_list ap;
	va_start(ap, fmt);
	vsnprintf(buf, sizeof(buf), fmt, ap);
	va_end(ap);
	out += buf;
}

// pick_tc() in nectar_v.cg
const char* attr_tc(int n) {
	switch (n) {
	case 0: return "aTexCoord0";
	case 1: return "aTexCoord1";
	case 2: return "aTexCoord2";
	default: return "aTexCoord3";
	}
}

bool mode_uses_matrix(uint8_t m) { return m >= 1 && m <= 14; }

void emit_diffuse_light(std::string& o, const char* acc, const char* pos, const char* col, const char* k, bool attn) {
	addf(o, "\t{ float3 Ld = %s.xyz - worldPos.xyz; float dist = length(Ld); half3 L = (half3)(Ld / max(dist, 0.001));\n", pos);
	o += "\t  half diff = max(dot(N, L), 0.0h);\n";
	if (attn) addf(o, "\t  diff *= (half)saturate(%s.x + %s.y * dist + %s.z * dist * dist);\n", k, k, k);
	addf(o, "\t  %s += diff * (half3)%s.rgb; }\n", acc, col);
}

} // namespace

std::string vita_cg_vertex_source_for(const VitaVsKey& k)
{
	return vita_cg_vertex_source_for(k, 0x1Fu);
}

std::string vita_cg_vertex_source_for(const VitaVsKey& k, unsigned needMask)
{
	std::string o;
	const int slots = k.paletteSlots < 1 ? 1 : k.paletteSlots;
	const bool c1Attr = k.pad[0] == 1;
	const bool needLit1 = (needMask & 0x10u) != 0 || c1Attr;
	const bool matRgb0 = (needMask & 0x20u) != 0, matAlpha0 = (needMask & 0x40u) != 0, matRgb1 = (needMask & 0x80u) != 0 && !c1Attr;
	const bool lit1Math = needLit1 && !c1Attr && k.chan1En && (k.chan1Mode == 1 || (k.chan1Mode == 0 && k.numLights1 > 0));

	// Texcoord slots to output and compute
	bool outTc[4], compTc[4];
	for (int s = 0; s < 4; ++s) { outTc[s] = (needMask & (1u << s)) != 0; compTc[s] = outTc[s]; }
	for (int s = 3; s >= 0; --s) {
		const uint8_t m = k.tcMode[s];
		if (compTc[s] && m >= 11 && m <= 14) { const int src = int(m) - 11; if (src < s) compTc[src] = true; }
	}
	bool needN = (k.chan0En && k.numLights0 > 0) || lit1Math;
	for (int s = 0; s < 4; ++s) if (compTc[s] && k.tcMode[s] == 2) needN = true;

	addf(o, "/* Generated by vita_vs_cg.cpp (VitaVsKey v%u, hash %llu, needMask 0x%02x): palette %d slot(s), "
	        "chan0 %s (%d light(s)%s), chan1 %s mode %d (%d light(s)%s), texgen %d/%d/%d/%d, normal %s. */\n",
	     (unsigned)k.version, (unsigned long long)vita_vs_hash_key(k), needMask, slots,
	     k.chan0En ? "lit" : "off", (int)k.numLights0, k.attn0 ? ", attn" : "",
	     k.chan1En ? "lit" : "off", (int)k.chan1Mode, (int)k.numLights1, k.attn1 ? ", attn" : "",
	     (int)k.tcMode[0], (int)k.tcMode[1], (int)k.tcMode[2], (int)k.tcMode[3], needN ? "yes" : "no");

	o += "void main(\n";
	o += "\tfloat3 aPos       : ATTR0,\n";
	o += "\tfloat4 aColor     : ATTR1,\n";
	o += "\tfloat3 aNormal    : ATTR2,\n";
	o += "\tfloat2 aTexCoord0 : ATTR3,\n";
	o += "\tfloat2 aTexCoord1 : ATTR4,\n";
	o += "\tfloat2 aTexCoord2 : ATTR5,\n";
	o += "\tfloat2 aTexCoord3 : ATTR6,\n";
	o += "\tfloat  aMtxIdx    : ATTR7,\n";
	o += "\tuniform float4x4 uProjMtx,\n";
	o += "\tuniform float4 uFogParams,\n";
	addf(o, "\tuniform float4 uPosPal[%d],\n", slots * 3);
	if (needN) addf(o, "\tuniform float4 uNrmPal[%d],\n", slots * 3);
	if (matRgb0 || matAlpha0) o += "\tuniform float4 uMaterialColor,\n";
	if (needLit1 && matRgb1) o += "\tuniform float4 uMaterialColor1,\n";
	if (k.chan0En) {
		o += "\tuniform float4 uAmbColor,\n";
		for (int i = 0; i < k.numLights0; ++i)
			addf(o, "\tuniform float4 uLightPos_%d, uniform float4 uLightColor_%d, uniform float4 uLightK_%d,\n", i, i, i);
	}
	if (needLit1 && !c1Attr && k.chan1En) {
		o += "\tuniform float4 uAmbColor1,\n";
		if (k.chan1Mode == 1)
			o += "\tuniform float4 uLightColor1_0, uniform float4 uSpecHalf1, uniform float4 uSpecAttn1,\n"
			     "\tuniform float4 uLightK1_0,\n";
		else if (k.chan1Mode == 0)
			for (int i = 0; i < k.numLights1; ++i)
				addf(o, "\tuniform float4 uLightPos1_%d, uniform float4 uLightColor1_%d, uniform float4 uLightK1_%d,\n", i, i, i);
	}
	for (int s = 0; s < 4; ++s)
		if (compTc[s] && mode_uses_matrix(k.tcMode[s])) addf(o, "\tuniform float4x4 uTcMtx_%d,\n", s);
	o += "\tout float4 out_position : POSITION,\n";
	o += "\tout float  vFog       : TEXCOORD6,\n";
	o += "\tout half4  vColor     : COLOR0,\n";
	if (needLit1) o += "\tout half4  vColor1    : TEXCOORD5,\n";
	for (int s = 0; s < 4; ++s)
		if (outTc[s]) addf(o, "\tout float2 vTexCoord%d : TEXCOORD%d,\n", s, s);
	if (o.size() >= 2 && o[o.size() - 2] == ',') o.erase(o.size() - 2, 1);
	o += ") {\n";

	if (slots > 1) o += "\tint mi = int(aMtxIdx) * 3;\n";
	else           o += "\tint mi = 0;\n";
	o += "\tfloat4 p4 = float4(aPos, 1.0);\n";
	o += "\tfloat4 worldPos = float4(dot(uPosPal[mi], p4), dot(uPosPal[mi + 1], p4), dot(uPosPal[mi + 2], p4), 1.0);\n";
	o += "\tout_position = mul(worldPos, uProjMtx);\n";
	// GX linear fog, per vertex
	o += "\tvFog = out_position.w * uFogParams.x + uFogParams.y;\n";
	if (needN)
		o += "\thalf3 N = (half3)normalize(float3(dot(uNrmPal[mi].xyz, aNormal), dot(uNrmPal[mi + 1].xyz, aNormal), dot(uNrmPal[mi + 2].xyz, aNormal)));\n";

	// Channel 0
	addf(o, "\thalf3 base0 = (half3)%s;\n", matRgb0 ? "uMaterialColor.rgb" : "aColor.rgb");
	addf(o, "\thalf alpha0 = (half)%s;\n", matAlpha0 ? "uMaterialColor.a" : "aColor.a");
	if (k.chan0En) {
		o += "\thalf3 lit0 = (half3)uAmbColor.rgb;\n";
		for (int i = 0; i < k.numLights0; ++i) {
			char pos[24], col[24], kk[24];
			snprintf(pos, sizeof(pos), "uLightPos_%d", i);
			snprintf(col, sizeof(col), "uLightColor_%d", i);
			snprintf(kk, sizeof(kk), "uLightK_%d", i);
			emit_diffuse_light(o, "lit0", pos, col, kk, k.attn0 != 0);
		}
		o += "\tvColor = half4(saturate(base0 * saturate(lit0)), alpha0);\n";
	} else {
		o += "\tvColor = half4(base0, alpha0);\n";   // unlit
	}

	// Channel 1
	if (c1Attr) {
		o += "\tvColor1 = half4((half3)aNormal, (half)aMtxIdx);\n";
	} else if (needLit1) {
		addf(o, "\thalf3 base1 = (half3)%s;\n", matRgb1 ? "uMaterialColor1.rgb" : "aColor.rgb");
		if (k.chan1En) {
			o += "\thalf3 lit1 = (half3)uAmbColor1.rgb;\n";
			if (k.chan1Mode == 1) {
				o += "\t{ half cosT = max(dot(N, (half3)normalize(uSpecHalf1.xyz)), 0.0h);\n";
				o += "\t  half3 quad = half3(1.0h, cosT, cosT * cosT);\n";
				o += "\t  half num = max(0.0h, dot((half3)uSpecAttn1.xyz, quad));\n";
				o += "\t  half den = dot((half3)uLightK1_0.xyz, quad);\n";
				o += "\t  half att = (den > 0.0001h) ? saturate(num / den) : 0.0h;\n";
				o += "\t  lit1 += att * (half3)uLightColor1_0.rgb; }\n";
			} else if (k.chan1Mode == 0) {
				for (int i = 0; i < k.numLights1; ++i) {
					char pos[24], col[24], kk[24];
					snprintf(pos, sizeof(pos), "uLightPos1_%d", i);
					snprintf(col, sizeof(col), "uLightColor1_%d", i);
					snprintf(kk, sizeof(kk), "uLightK1_%d", i);
					emit_diffuse_light(o, "lit1", pos, col, kk, k.attn1 != 0);
				}
			}
			o += "\tvColor1 = half4(saturate(base1 * saturate(lit1)), alpha0);\n";
		} else {
			o += "\tvColor1 = half4(base1, alpha0);\n";
		}
	}

	for (int s = 0; s < 4; ++s) {
		if (!compTc[s]) continue;
		const uint8_t m = k.tcMode[s];
		char expr[160];
		if (m == 1) {
			snprintf(expr, sizeof(expr), "mul(worldPos, uTcMtx_%d).xy", s);
		} else if (m == 2) {
			snprintf(expr, sizeof(expr), "mul(float4(N, 1.0), uTcMtx_%d).xy", s);
		} else if (m >= 3 && m <= 10) {
			snprintf(expr, sizeof(expr), "mul(float4(%s, 0.0, 1.0), uTcMtx_%d).xy", attr_tc(int(m) - 3), s);
		} else if (m >= 11 && m <= 14) {
			const int src = int(m) - 11;
			if (src < s) snprintf(expr, sizeof(expr), "mul(float4(tc%d, 0.0, 1.0), uTcMtx_%d).xy", src, s);
			else         snprintf(expr, sizeof(expr), "mul(float4(0.0, 0.0, 0.0, 1.0), uTcMtx_%d).xy", s);
		} else if (m >= 20 && m <= 27) {
			snprintf(expr, sizeof(expr), "%s", attr_tc(int(m) - 20));
		} else {
			snprintf(expr, sizeof(expr), "%s", attr_tc(s));
		}
		addf(o, "\tfloat2 tc%d = %s;\n", s, expr);
	}
	for (int s = 0; s < 4; ++s)
		if (outTc[s]) addf(o, "\tvTexCoord%d = tc%d;\n", s, s);
	o += "}\n";
	return o;
}
